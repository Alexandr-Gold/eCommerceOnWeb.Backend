namespace eCommerceOnWeb.Backend.Domain.Aggregates.ProductAggregate
{
    /*
     * ProductStatus описывает жизненный цикл товара.
     *
     * На текущем этапе используется обычный enum,
     * так как количество состояний ограничено, а правила переходов
     * находятся внутри агрегата Product.
     *
     * При дальнейшем развитии приложения, когда:
     * - количество состояний увеличится;
     * - появится большое количество правил переходов;
     * - разные части системы начнут использовать логику статусов;
     *
     * рекомендуется перейти на Smart Enum или отдельный Value Object,
     * чтобы инкапсулировать поведение статусов:
     *
     * CanActivate()
     * CanDeactivate()
     * CanDiscontinue()
     * IsTerminal()
     *
     * Smart Enum не применяется сейчас намеренно,
     * чтобы избежать преждевременного усложнения доменной модели.
     */

    public enum ProductStatus
    {
        /// <summary>
        /// Товар создан, но еще не опубликован.
        /// </summary>
        Draft = 0,

        /// <summary>
        /// Товар доступен для продажи.
        /// </summary>
        Active = 1,

        /// <summary>
        /// Товар временно снят с продажи.
        /// </summary>
        Inactive = 2,

        /// <summary>
        /// Товар снят с производства навсегда.
        /// Возврат в продажу запрещен.
        /// </summary>
        Discontinued = 3
    }
}
